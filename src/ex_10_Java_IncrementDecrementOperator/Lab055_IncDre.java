package ex_10_Java_IncrementDecrementOperator;

public class Lab055_IncDre {
    public static void main(String[] args) {
        int a = 10;
        int b = ++a;
        System.out.println(a);
        System.out.println(b);

        // Line 5 | a=10 | NA
        // Line 6 | a=11 | b=11
        // Line 7 | a=11
        // Line 8 | b=11
    }
}
