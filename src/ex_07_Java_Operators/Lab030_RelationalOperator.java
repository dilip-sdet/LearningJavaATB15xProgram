package ex_07_Java_Operators;

public class Lab030_RelationalOperator {
    public static void main(String[] args) {
        /*
        < -> Less than
        <= -> Less than or equal to
        > -> Greater than
        >= -> Greater than or equal to
        == -> equal to(checking both values)
        != -> Not equal
         */

        int a = 10;
        int b = 20;
        System.out.println(a < b);
        System.out.println(a == b);
        System.out.println(a > b);
        System.out.println(a >= b);
        System.out.println(a <= b);
        System.out.println(a != b);


    }
}
