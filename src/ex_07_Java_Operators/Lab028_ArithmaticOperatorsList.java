package ex_07_Java_Operators;

public class Lab028_ArithmaticOperatorsList {
    public static void main(String[] args) {
        /*
        List of Arithmatic Operator:
        -> "+" Addition
        -> "-" Substraction
        -> "*" Multiplication
        -> "/" Division
        -> "%" Modulus
         */

        int a = 41;
        int b = 20;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);

    }
}
