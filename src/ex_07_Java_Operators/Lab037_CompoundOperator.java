package ex_07_Java_Operators;

public class Lab037_CompoundOperator {
    public static void main(String[] args) {
        int a = 50;
        System.out.println(a += 10);
        System.out.println(a -= 10);
        System.out.println(a *= 10);
        System.out.println(a /= 10);
        System.out.println(a %= 10);

    }
}
