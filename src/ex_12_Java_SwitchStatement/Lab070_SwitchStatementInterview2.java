package ex_12_Java_SwitchStatement;

public class Lab070_SwitchStatementInterview2 {
    public static void main(String[] args) {
        char ch = 'A';
        switch (ch) {
            case 65:
                System.out.println("ACSII matched");
                break;
            case 66:
                System.out.println("ACSII not matched");
                break;
        }
    }
}
