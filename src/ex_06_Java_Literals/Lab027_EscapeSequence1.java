package ex_06_Java_Literals;

public class Lab027_EscapeSequence1 {
    public static void main(String[] args) {
         /*
        \n - next line
        \t - tab space
        \b - backspace
        \r - carriage return
         */
        System.out.println(("Dilip\nKumar"));
        System.out.println(("Dilip\tKumar"));
        System.out.println(("Dilip \bKumar"));
        System.out.println(("Dilip\rKumar"));
    }
}


